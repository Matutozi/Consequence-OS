#!/usr/bin/env bash
# Creates .env with fresh random secrets for local use and docker compose.
# An existing .env is never overwritten: only secrets it lacks are added,
# so upgrading keeps the keys you already have.
set -euo pipefail

SECRETS=(
  CONSEQUENCE_KEY_SUPPORT_BOT
  CONSEQUENCE_KEY_RECEIVER_PAYMENTS
  CONSEQUENCE_ADMIN_TOKEN
  CONSEQUENCE_SIGNING_KEY_ED25519
  CONSEQUENCE_SIGNING_KEY_MLDSA87
  POSTGRES_PASSWORD
)

# 32 random bytes as base64url without padding: the format the signing keys use.
b64url32() { head -c 32 /dev/urandom | base64 | tr '+/' '-_' | tr -d '=\n'; }

umask 077 # only you can read the file
if [[ ! -e .env ]]; then
  echo "# Generated by scripts/setup-env.sh. Secrets: never commit this file." > .env
fi

added=0
for name in "${SECRETS[@]}"; do
  if ! grep -q "^$name=" .env; then
    echo "$name=$(b64url32)" >> .env
    added=$((added + 1))
  fi
done
echo ".env is ready ($added new secrets added)."
